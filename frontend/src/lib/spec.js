// Builds a "SPEC.md" wrapper around a converted document: the original markdown
// plus instructions for Claude Code to scaffold a project from it. Handy for
// turning a converted brief/spec/transcript straight into actionable work.
export function buildSpecMarkdown(entry) {
  const { sourceName, outputName, kind, markdown, charCount } = entry
  return `# SPEC.md

> Generated by **File → Markdown**. Source: \`${sourceName}\` (${kind}, ${charCount.toLocaleString()} chars).

## Instructions for Claude Code

You are scaffolding a project from the source document below. Follow these steps:

1. Read the **Source Content** section carefully and extract the concrete
   requirements, entities, and constraints it describes.
2. Propose a minimal folder structure and tech stack appropriate to the content.
3. Implement the project incrementally, stating what you create before each file.
4. Add a short README explaining how to run it.
5. Keep everything production-ready — no stubs or TODOs.

If the document is a transcript, treat the spoken requirements as the spec.
If it is data (CSV/JSON), infer a schema and build tooling around it.

## Source Content

> Origin file: \`${outputName}\`

${markdown}
`
}
